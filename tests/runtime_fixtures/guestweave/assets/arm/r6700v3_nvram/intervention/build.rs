//! Parses manifest.json and emits OUT_DIR/fmst_manifest.rs with the
//! StaticManifest definition + fmst_manifest() export.

use std::io::Write;

fn main() {
    println!("cargo:rerun-if-changed=manifest.json");
    println!("cargo:rerun-if-changed=build.rs");

    let manifest_text = std::fs::read_to_string("manifest.json")
        .expect("failed to read manifest.json");
    let m: serde_json::Value = serde_json::from_str(&manifest_text)
        .expect("invalid JSON");

    let out_dir = std::env::var_os("OUT_DIR").expect("OUT_DIR not set");
    let out_path = std::path::PathBuf::from(out_dir).join("fmst_manifest.rs");
    let mut out = std::fs::File::create(&out_path).expect("open OUT_DIR file");

    writeln!(out, "// generated by build.rs from manifest.json - do not edit").unwrap();
    writeln!(out).unwrap();
    writeln!(out, "use fmst_iib_api::manifest::*;").unwrap();
    writeln!(out, "use fmst_iib_api::types::*;").unwrap();

    // Callsite hooks.
    let empty = vec![];
    writeln!(out, "static CALLSITE_HOOKS: &[CallsiteHookStatic] = &[").unwrap();
    for h in m["callsite_hooks"].as_array().unwrap_or(&empty) {
        let id = h["id"].as_str().unwrap();
        let bin = h["target"]["binary"].as_str().unwrap();
        let off_str = h["target"]["offset"].as_str().unwrap();
        let off: u64 = u64::from_str_radix(off_str.trim_start_matches("0x"), 16).unwrap();
        let hint = h["target"].get("_symbol_hint").and_then(|v| v.as_str());
        let flavor = h["flavor"].as_str().unwrap();
        let entry = h["entry_fn_path"].as_str().unwrap();

        writeln!(out, "    CallsiteHookStatic {{").unwrap();
        writeln!(out, "        id: \"{id}\",").unwrap();
        writeln!(out, "        target: ModuleTargetStatic {{").unwrap();
        writeln!(out, "            binary: \"{bin}\",").unwrap();
        writeln!(out, "            offset: {off:#x},").unwrap();
        match hint {
            Some(h) => writeln!(out, "            symbol_hint: Some(\"{h}\"),").unwrap(),
            None    => writeln!(out, "            symbol_hint: None,").unwrap(),
        }
        writeln!(out, "        }},").unwrap();
        writeln!(out, "        flavor: HookFlavor::{flavor},").unwrap();
        writeln!(out, "        entry_fn: {entry},").unwrap();
        writeln!(out, "    }},").unwrap();
    }
    writeln!(out, "];").unwrap();

    // Function stubs.
    writeln!(out, "static FUNCTION_STUBS: &[FunctionStubStatic] = &[").unwrap();
    for h in m["function_stubs"].as_array().unwrap_or(&empty) {
        let id = h["id"].as_str().unwrap();
        let bin = h["target"]["binary"].as_str().unwrap();
        let off_str = h["target"]["offset"].as_str().unwrap();
        let off: u64 = u64::from_str_radix(off_str.trim_start_matches("0x"), 16).unwrap();
        let hint = h["target"].get("_symbol_hint").and_then(|v| v.as_str());
        let flavor = h["flavor"].as_str().unwrap();
        let entry = h["entry_fn_path"].as_str().unwrap();

        writeln!(out, "    FunctionStubStatic {{").unwrap();
        writeln!(out, "        id: \"{id}\",").unwrap();
        writeln!(out, "        target: ModuleTargetStatic {{").unwrap();
        writeln!(out, "            binary: \"{bin}\",").unwrap();
        writeln!(out, "            offset: {off:#x},").unwrap();
        match hint {
            Some(h) => writeln!(out, "            symbol_hint: Some(\"{h}\"),").unwrap(),
            None    => writeln!(out, "            symbol_hint: None,").unwrap(),
        }
        writeln!(out, "        }},").unwrap();
        writeln!(out, "        flavor: HookFlavor::{flavor},").unwrap();
        writeln!(out, "        entry_fn: {entry},").unwrap();
        writeln!(out, "    }},").unwrap();
    }
    writeln!(out, "];").unwrap();

    // Pseudo files.
    writeln!(out, "static PSEUDO_FILES: &[PseudoFileStatic] = &[").unwrap();
    for f in m["pseudo_files"].as_array().unwrap_or(&empty) {
        let id = f["id"].as_str().unwrap();
        let factory = f["factory_path"].as_str().unwrap();
        let impl_name = f["impl_type_path"].as_str().unwrap().rsplit("::").next().unwrap();

        writeln!(out, "    PseudoFileStatic {{").unwrap();
        writeln!(out, "        id: \"{id}\",").unwrap();
        writeln!(out, "        paths: &[").unwrap();
        for p in f["paths"].as_array().unwrap() {
            writeln!(out, "            \"{}\",", p.as_str().unwrap()).unwrap();
        }
        writeln!(out, "        ],").unwrap();
        writeln!(out, "        factory: {factory},").unwrap();
        writeln!(out, "        impl_name: \"{impl_name}\",").unwrap();
        writeln!(out, "    }},").unwrap();
    }
    writeln!(out, "];").unwrap();

    // Global state init.
    let gs_init = m["global_state"]["init_path"].as_str().unwrap();
    writeln!(out, "fn _iib_init_global_state() -> Box<dyn std::any::Any + Send + Sync> {{").unwrap();
    writeln!(out, "    Box::new({gs_init}())").unwrap();
    writeln!(out, "}}").unwrap();

    let abi = m["manifest_abi_version"].as_u64().unwrap();
    let arch = m["arch"].as_str().unwrap();
    let arch_variant = match arch {
        "arm" => "Arm", "mips" => "Mips", "x86_64" => "X86_64",
        _ => panic!("unknown arch {arch}"),
    };

    writeln!(out, "
static MANIFEST: StaticManifest = StaticManifest {{
    abi_version: {abi},
    arch: Arch::{arch_variant},
    global_state: StaticGlobalState {{
        type_name: \"GlobalState\",
        init_fn: _iib_init_global_state,
    }},
    callsite_hooks: CALLSITE_HOOKS,
    function_stubs: FUNCTION_STUBS,
    pseudo_files: PSEUDO_FILES,
}};

#[no_mangle]
pub extern \"Rust\" fn fmst_manifest() -> &'static StaticManifest {{
    &MANIFEST
}}
").unwrap();
}
