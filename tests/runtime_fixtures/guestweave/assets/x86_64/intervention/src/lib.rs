//! IIB intervention for the x86_64 self-contained nvram demo.
//!
//! Mirrors the ARM R6700v3 nvram intervention but targets the
//! `fmst_x86_nvram_guest` ET_EXEC binary. The four nvram_* functions
//! and the outer `guarded_network_startup` all live in that single ELF.
//!
//! # Unsafe code policy
//!
//! The Cargo.toml sets `unsafe_code = "deny"` crate-wide, and each
//! user-authored module below adds `#![forbid(unsafe_code)]` at its own
//! top so that it's statically impossible to introduce unsafe code
//! inside a stub without deleting the attribute. The only sanctioned
//! unsafety in this crate is the `#[unsafe(no_mangle)]` on the manifest
//! export, generated by build.rs — isolated below with an explicit
//! `#[allow(unsafe_code)]`.

pub mod function_stubs;
pub mod state;

#[allow(unsafe_code)]
mod manifest_export {
    include!(concat!(env!("OUT_DIR"), "/fmst_manifest.rs"));
}
pub use manifest_export::fmst_manifest;
